#!/usr/bin/env node
// Generates src/pipeline/_confusion-case-tables.ts: per-encoding letter/case
// byte tables for the encodings named by confusion.bin pairs.
//
// chardet's confusion._letter_case_table builds these at runtime with
// Python's codecs + unicodedata (0 = non-letter, 1 = uppercase letter, 2 = other
// letter, combining marks counting as letters). TextDecoder cannot stand in:
// several pair encodings (the EBCDIC pages among them) have no WHATWG
// decoder at all. So the tables are precomputed here by running chardet's own
// implementation over the pinned submodule — the source of truth — and
// shipped as 256-char digit strings.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { chardetVersion } from './chardet-version.js';
import { chardet7SrcDir, ensureChardet7 } from './lib/chardet.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(root, 'src', 'pipeline', '_confusion-case-tables.ts');

const PY = `
import json, sys
from chardet.pipeline.confusion import load_confusion_data, _letter_case_table
encodings = sorted({enc for pair in load_confusion_data() for enc in pair})
tables = {enc: "".join(str(v) for v in _letter_case_table(enc)) for enc in encodings}
json.dump(tables, sys.stdout)
`;

export function generate() {
  ensureChardet7(root);
  const out = execFileSync('python3', ['-c', PY], {
    env: { ...process.env, PYTHONPATH: chardet7SrcDir(root) },
    encoding: 'utf8',
  });
  const tables = JSON.parse(out);

  const entries = Object.entries(tables)
    .map(([enc, table]) => `  ${JSON.stringify(enc)}:\n    ${JSON.stringify(table)},`)
    .join('\n');

  const version = chardetVersion();
  writeFileSync(
    outputPath,
    `// generated by scripts/generate-confusion-case-tables.js — do not edit manually\n` +
    `// chardet ${version}\n` +
    `//\n` +
    `// Per-encoding byte tables for confusion category voting, one 256-char\n` +
    `// digit string per encoding named in confusion.bin: 0 = non-letter,\n` +
    `// 1 = uppercase letter, 2 = other letter (combining marks count as\n` +
    `// letters). Precomputed from chardet's confusion._letter_case_table.\n` +
    `export const CONFUSION_CASE_TABLES: Readonly<Record<string, string>> = Object.freeze({\n` +
    `${entries}\n` +
    `});\n`,
    'utf8',
  );

  console.log(`Wrote ${Object.keys(tables).length} case tables to src/pipeline/_confusion-case-tables.ts`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generate();
}
